#!/usr/bin/env bash
# Installs the game data from the original CD image, replacing the Wine-based
# install. Accepts an .iso file (mounted read-only with hdiutil on macOS) or a
# directory where the CD is already mounted or copied.
#
#   scripts/install-from-iso.sh [-l language] [-b binary] [-a apps-dir] <image.iso|cd-dir> <destination>
#
# On macOS it also creates an application bundle in apps-dir (default
# ~/Applications) with the icon the original installer used for its shortcut.
# The game binary defaults to build/<game> or to the copy next to this script.
#
# Supported: Need for Speed II SE.
set -euo pipefail

script_dir="$(cd "$(dirname "$0")" && pwd)"

usage()
{
    sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'
    exit 1
}

die()
{
    echo "error: $*" >&2
    exit 1
}

# Case-insensitive lookup of one entry inside a directory (CD names are
# upper case, but copies of the CD may not be).
find_entry()
{
    local dir="$1" name="$2" entry
    for entry in "$dir"/*; do
        if [[ "$(basename "$entry" | tr '[:upper:]' '[:lower:]')" == "$(echo "$name" | tr '[:upper:]' '[:lower:]')" ]]; then
            echo "$entry"
            return 0
        fi
    done
    return 1
}

language="english"
binary=""
apps_dir="$HOME/Applications"
while getopts "l:b:a:h" opt; do
    case "$opt" in
        l) language="$(echo "$OPTARG" | tr '[:upper:]' '[:lower:]')" ;;
        b) binary="$OPTARG" ;;
        a) apps_dir="$OPTARG" ;;
        *) usage ;;
    esac
done
shift $((OPTIND - 1))
[[ $# -eq 2 ]] || usage

source="$1"
destination="$2"
mountpoint=""
workdir="$(mktemp -d "${TMPDIR:-/tmp}/nfs-install.XXXXXX")"

cleanup()
{
    if [[ -n "$mountpoint" ]]; then
        hdiutil detach -quiet "$mountpoint" || true
    fi
    rm -rf "$workdir"
}
trap cleanup EXIT

if [[ -f "$source" ]]; then
    command -v hdiutil >/dev/null || die "mounting an image needs hdiutil (macOS); mount it yourself and pass the directory"
    mountpoint="$workdir/cd"
    mkdir "$mountpoint"
    echo "Mounting $source"
    hdiutil attach -readonly -nobrowse -quiet -mountpoint "$mountpoint" "$source" \
        || die "could not mount $source"
    cd_dir="$mountpoint"
elif [[ -d "$source" ]]; then
    cd_dir="$source"
else
    die "$source is neither an image file nor a directory"
fi

find_binary()
{
    local game="$1" candidate
    for candidate in "$binary" "$script_dir/../build/$game" "$script_dir/$game"; do
        if [[ -n "$candidate" && -x "$candidate" ]]; then
            echo "$candidate"
            return 0
        fi
    done
    return 1
}

# macOS application bundle: the game binary with its SDL3 library, a launcher
# that passes the data directory, and the original shortcut icon.
create_app()
{
    local name="$1" game="$2" icon="$3" game_binary app sdl sdl_path size iconset
    [[ "$(uname)" == "Darwin" ]] || return 0
    if ! game_binary="$(find_binary "$game")"; then
        echo "No $game binary found (build it or pass -b); skipping the application bundle"
        return 0
    fi

    app="$apps_dir/$name.app"
    echo "Creating $app"
    rm -rf "$app"
    mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources" "$app/Contents/Frameworks"
    cp "$game_binary" "$app/Contents/MacOS/$game"

    # Bundle SDL3 so the application does not depend on where it was built
    sdl="$(otool -L "$game_binary" | awk '/libSDL3/ { print $1 }')"
    if [[ -n "$sdl" ]]; then
        sdl_path="${sdl/@executable_path/$(dirname "$game_binary")}"
        sdl_path="${sdl_path/@rpath/$(dirname "$game_binary")}"
        cp -L "$sdl_path" "$app/Contents/Frameworks/"
        install_name_tool -change "$sdl" "@executable_path/../Frameworks/$(basename "$sdl")" \
            "$app/Contents/MacOS/$game" 2>/dev/null
        codesign --force --sign - "$app/Contents/Frameworks/$(basename "$sdl")"
    fi
    # install_name_tool invalidates the signature, and arm64 requires one
    codesign --force --sign - "$app/Contents/MacOS/$game"

    cat > "$app/Contents/MacOS/launch" <<EOF
#!/bin/sh
# Generated by install-from-iso.sh: starts the game with its data directory
exec "\$(dirname "\$0")/$game" "$destination"
EOF
    chmod +x "$app/Contents/MacOS/launch"

    iconset="$workdir/AppIcon.iconset"
    mkdir -p "$iconset"
    for size in 16 32 128 256 512; do
        python3 -I "$script_dir/ico-to-png.py" "$icon" "$iconset/icon_${size}x${size}.png" "$size"
        python3 -I "$script_dir/ico-to-png.py" "$icon" "$iconset/icon_${size}x${size}@2x.png" "$((size * 2))"
    done
    iconutil -c icns "$iconset" -o "$app/Contents/Resources/AppIcon.icns"

    cat > "$app/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key>
    <string>io.github.nfs-recompiled.$game</string>
    <key>CFBundleName</key>
    <string>$name</string>
    <key>CFBundleDisplayName</key>
    <string>$name</string>
    <key>CFBundleExecutable</key>
    <string>launch</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.racing-games</string>
    <key>LSMinimumSystemVersion</key>
    <string>11.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
</dict>
</plist>
EOF
    touch "$app"
    echo "Open it from Launchpad, Spotlight or: open \"$app\""
}

install_nfs2se()
{
    local manifest fedata gamedata exe icon
    case "$language" in
        english|german|french|spanish|italian|swedish) ;;
        *) die "unknown language '$language' (english, german, french, spanish, italian, swedish)" ;;
    esac
    manifest="$(find_entry "$cd_dir" install.nfs)" || die "INSTALL.NFS not found on the CD"
    fedata="$(find_entry "$cd_dir" fedata)"        || die "FEDATA not found on the CD"
    gamedata="$(find_entry "$cd_dir" gamedata)"    || die "GAMEDATA not found on the CD"
    exe="$(find_entry "$cd_dir" nfs2sen.exe)"      || die "NFS2SEN.EXE not found on the CD"
    icon="$(find_entry "$cd_dir" nfs2sen.ico)"     || die "NFS2SEN.ICO not found on the CD"

    echo "Copying FEDATA and GAMEDATA to $destination"
    cp -R "$fedata" "$gamedata" "$destination/"
    # The game looks for X:NFS2SEN.EXE to detect its CD; the CD directory is
    # the install directory when the game is started with a single path.
    cp "$exe" "$destination/"
    chmod -R u+w "$destination"

    # install.win is the CD manifest with the chosen language: three flag
    # characters per line, then the language, "local" and the data paths. All
    # paths stay relative (.\) because everything is copied locally.
    awk -v language="$language" \
        'NR == 1 { printf "4nn%s\r\n", language; next } { print }' \
        "$manifest" > "$destination/install.win"

    # The original installer gave the nfs2sen.exe shortcut this icon
    create_app "Need for Speed II SE" nfs2se "$icon"
}

mkdir -p "$destination"
destination="$(cd "$destination" && pwd)"

if find_entry "$cd_dir" nfs2sen.exe >/dev/null; then
    echo "Need for Speed II SE detected"
    install_nfs2se
    game="nfs2se"
else
    die "unrecognised CD: no NFS2SEN.EXE in $cd_dir"
fi

echo "Done. Run the game with:"
echo "  ./build/$game \"$destination\""
